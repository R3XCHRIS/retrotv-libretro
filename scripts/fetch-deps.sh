#!/usr/bin/env bash
# Fetch FFmpeg 7.1 public headers (matching ReplayOS's libavformat.so.61 etc.)
# into deps/ffmpeg. Headers only - the libraries are loaded on the Pi at runtime.
set -euo pipefail
cd "$(dirname "$0")/.."
TAG="${FFMPEG_TAG:-n7.1}"
DEST=deps/ffmpeg
if [[ -f "$DEST/.tag" && "$(cat "$DEST/.tag")" == "$TAG" ]]; then
  echo "deps: FFmpeg $TAG headers already present"; exit 0
fi
rm -rf "$DEST"
git clone -q --depth 1 --branch "$TAG" --filter=blob:none --sparse https://github.com/FFmpeg/FFmpeg "$DEST"
git -C "$DEST" sparse-checkout set --no-cone \
  '/libavutil/*.h' '/libavcodec/*.h' '/libavformat/*.h' '/libswscale/*.h' '/libswresample/*.h'
rm -rf "$DEST/.git"
# avconfig.h is normally generated by ./configure
cat >"$DEST/libavutil/avconfig.h" <<'EOF'
/* Generated by scripts/fetch-deps.sh (aarch64 / x86_64 little-endian) */
#ifndef AVUTIL_AVCONFIG_H
#define AVUTIL_AVCONFIG_H
#define AV_HAVE_BIGENDIAN 0
#define AV_HAVE_FAST_UNALIGNED 1
#endif
EOF
echo "$TAG" >"$DEST/.tag"
echo "deps: FFmpeg $TAG headers in $DEST"
